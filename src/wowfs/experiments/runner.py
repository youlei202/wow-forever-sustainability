"""Immutable development manifests and resumable complete-instance checkpoints."""
from __future__ import annotations
import concurrent.futures
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import signal
import shutil
import subprocess
import sys
import time
import traceback
import yaml
from wowfs.paths import SOURCE_ROOT, atomic_json, canonical_hash, source_hash

def load_config(path: Path) -> dict:
    return yaml.safe_load(path.read_text())

def freeze(config: dict, root: Path) -> tuple[Path, dict]:
    if config.get("scope") != "abstract_exact":
        raise RuntimeError("Native protocol cannot be frozen: engine, tasks and behavior scale are not established. main_frozen.yaml is a design template.")
    from wowfs.experiments.exact import PROTOCOL
    protocol = {"config": config, "model_protocol": PROTOCOL, "config_hash": canonical_hash(config), "source_hash": source_hash(),
                "engine_hash": "none-abstract-deterministic-model", "split": config["split"],
                "scope": config["scope"], "commit": "uncommitted-no-git-identity",
                "future_access": "full terminal table is generated by enumerator; selection code slices current visible configurations and effect annotations, never future performance rows",
                "uncertainty": "deterministic model values; no combat sampling intervals",
                "native_protocol_frozen": False}
    run_id = f"{config['split']}-{canonical_hash(protocol)[:12]}"
    path = root / "runs" / run_id
    path.mkdir(parents=True, exist_ok=True)
    target = path / "FROZEN_PROTOCOL.json"
    if target.exists() and json.loads(target.read_text()) != protocol:
        raise RuntimeError("Frozen protocol collision; will not overwrite")
    atomic_json(target, protocol)
    snapshot = path / "source_snapshot"
    if not snapshot.exists():
        snapshot.mkdir()
        for source in (SOURCE_ROOT / "src").rglob("*.py"):
            destination = snapshot / source.relative_to(SOURCE_ROOT / "src")
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
        atomic_json(path / "SOURCE_SNAPSHOT_HASHES.json", {
            str(p.relative_to(snapshot)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(snapshot.rglob("*.py"))})
    expected = json.loads((path / "SOURCE_SNAPSHOT_HASHES.json").read_text())
    actual = {str(p.relative_to(snapshot)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in sorted(snapshot.rglob("*.py"))}
    if expected != actual:
        raise RuntimeError("Frozen source snapshot was modified")
    return path, protocol

def _one(seed: int, variant: str, horizon: int, directory: Path) -> dict:
    env = dict(os.environ)
    env["PYTHONPATH"] = str(directory / "source_snapshot")
    process = subprocess.run([sys.executable, "-m", "wowfs.experiments.worker", str(seed), variant, str(horizon)],
                             env=env, cwd=directory, capture_output=True, text=True, timeout=900)
    if process.returncode:
        raise RuntimeError(process.stderr[-20000:])
    return json.loads(process.stdout)

def run(config: dict, root: Path, resume: bool, workers: int | None = None) -> Path:
    directory, protocol = freeze(config, root)
    jobs = [(int(seed), variant) for variant in config["variants"] for seed in config["seeds"]]
    manifest = [{"sequence_id": f"{variant}-{seed}", "seed": seed, "variant": variant,
                 "horizon": config["horizon"], "scope": "abstract_exact",
                 "context": "abstract_no_class_or_race", "split": config["split"],
                 "sequence_hash": canonical_hash({"seed": seed, "variant": variant, "horizon": config["horizon"], "source": protocol["source_hash"]})}
                for seed, variant in jobs]
    # Seal the actual reveal orders and full finite-domain targets before any
    # method runs. Selection routines use only currently visible rows; the
    # enumerator owns the full terminal table for reproducibility and diagnostics.
    from wowfs.experiments.exact import build_domain
    import numpy as np
    table_dir = root / "data" / directory.name
    table_dir.mkdir(parents=True, exist_ok=True)
    for row in manifest:
        domain = build_domain(row["seed"], row["variant"])
        row["reveal_order"] = list(domain.order[:config["horizon"]])
        row["table_sha256"] = hashlib.sha256(domain.response.tobytes()).hexdigest()
        row["proposals"] = [{"round": i + 1, "slot": slot, "choice": 2,
                             "source": f"release_{i+1}", "visible_from": i + 1}
                            for i, slot in enumerate(row["reveal_order"])]
        table = table_dir / f"{row['sequence_id']}.npz"
        if not table.exists():
            np.savez_compressed(table, configurations=domain.configurations,
                                response=domain.response, base_response=domain.base_response,
                                initial_scale=domain.scale, cap=domain.cap)
        row["table_file"] = str(table)
        row["table_file_sha256"] = hashlib.sha256(table.read_bytes()).hexdigest()
    atomic_json(directory / "SEQUENCE_MANIFEST.json", manifest)
    pending = []
    for row in manifest:
        target = directory / "checkpoints" / f"{row['sequence_id']}.json"
        if resume and target.exists():
            saved = json.loads(target.read_text())
            if saved["protocol"] != protocol or saved["manifest"] != row:
                raise RuntimeError("Checkpoint protocol mismatch")
            if saved.get("status") == "complete":
                continue
        elif target.exists():
            raise RuntimeError("Checkpoint exists; use --resume")
        pending.append(row)
    stopped = False
    def request_stop(signum, frame):
        nonlocal stopped
        stopped = True
        print("Stop requested; finishing active instances and saving checkpoints.", flush=True)
    previous = {sig: signal.signal(sig, request_stop) for sig in (signal.SIGTERM, signal.SIGINT)}
    started = time.monotonic()
    max_workers = max(1, min(int(workers or config.get("workers", 2)), 64))
    state = {"status": "running", "pid": os.getpid(), "started_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
             "total_instances": len(jobs), "pending_at_start": len(pending), "workers": max_workers,
             "checkpoint_granularity": "complete instance; each checkpoint contains all per-round states"}
    atomic_json(directory / "RUN_STATE.json", state)
    failures = 0
    try:
        with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as executor:
            active = {}
            while pending or active:
                while pending and len(active) < max_workers and not stopped:
                    row = pending.pop(0)
                    future = executor.submit(_one, row["seed"], row["variant"], config["horizon"], directory)
                    active[future] = row
                if not active:
                    break
                done, _ = concurrent.futures.wait(active, timeout=1, return_when=concurrent.futures.FIRST_COMPLETED)
                for future in done:
                    row = active.pop(future)
                    record = {"protocol": protocol, "manifest": row}
                    try:
                        record.update({"status": "complete", "result": future.result()})
                    except Exception:
                        failures += 1
                        record.update({"status": "crash", "error": traceback.format_exc()})
                    atomic_json(directory / "checkpoints" / f"{row['sequence_id']}.json", record)
                    print(f"{row['sequence_id']}: {record['status']}", flush=True)
        state.update(status="stopped" if stopped else ("completed_with_crashes" if failures else "complete"),
                     elapsed_seconds=time.monotonic()-started, remaining=len(pending), crashes_this_invocation=failures)
        atomic_json(directory / "RUN_STATE.json", state)
        atomic_json(root / "runs/LATEST.json", {"run_dir": str(directory)})
    finally:
        for sig, handler in previous.items():
            signal.signal(sig, handler)
    if failures:
        raise RuntimeError(f"{failures} instances crashed; checkpoints retained")
    return directory
